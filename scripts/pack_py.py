"""
STARAPP PYTHON CODE BUNDLER
Generates js/starapp_bundle.js containing the source of all starapp/*.py files.
Enables Pyodide to write them to its in-memory virtual filesystem instantly,
ensuring offline execution and zero CORS issues on both file:/// and http:// origins.
"""

import os
import json
import base64

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
STARAPP_DIR = os.path.join(ROOT_DIR, "starapp")
OUTPUT_FILE = os.path.join(ROOT_DIR, "js", "starapp_bundle.js")

def pack():
    modules = {}
    for root, dirs, files in os.walk(STARAPP_DIR):
        if "__pycache__" in root:
            continue
        for filename in sorted(files):
            if filename.endswith(".py"):
                path = os.path.join(root, filename)
                rel_path = os.path.relpath(path, ROOT_DIR).replace("\\", "/")
                with open(path, "r", encoding="utf-8") as f:
                    content = f.read()
                modules[rel_path] = content

    db_path = os.path.join(ROOT_DIR, "data", "starapp.db")
    db_b64 = ""
    if os.path.exists(db_path):
        with open(db_path, "rb") as f:
            db_b64 = base64.b64encode(f.read()).decode("ascii")

    bundle_json = json.dumps(modules, indent=2)
    js_content = f"// Auto-generated by scripts/pack_py.py\nwindow.__STARAPP_PYTHON_MODULES__ = {bundle_json};\nwindow.__STARAPP_AUTHORITATIVE_SQLITE_B64__ = \"{db_b64}\";\n"

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Packed {len(modules)} Python modules + authoritative SQLite DB ({len(db_b64)} b64 chars) into {OUTPUT_FILE}")

if __name__ == "__main__":
    pack()

