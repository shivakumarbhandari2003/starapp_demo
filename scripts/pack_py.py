"""
STARAPP PYTHON CODE BUNDLER
Generates js/starapp_bundle.js containing the source of all starapp/*.py files.
Enables Pyodide to write them to its in-memory virtual filesystem instantly,
ensuring offline execution and zero CORS issues on both file:/// and http:// origins.
"""

import os
import json

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
STARAPP_DIR = os.path.join(ROOT_DIR, "starapp")
OUTPUT_FILE = os.path.join(ROOT_DIR, "js", "starapp_bundle.js")

def pack():
    modules = {}
    for filename in sorted(os.listdir(STARAPP_DIR)):
        if filename.endswith(".py"):
            path = os.path.join(STARAPP_DIR, filename)
            with open(path, "r", encoding="utf-8") as f:
                content = f.read()
            virtual_path = f"starapp/{filename}"
            modules[virtual_path] = content

    bundle_json = json.dumps(modules, indent=2)
    js_content = f"// Auto-generated by scripts/pack_py.py\nwindow.__STARAPP_PYTHON_MODULES__ = {bundle_json};\n"

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Packed {len(modules)} Python modules into {OUTPUT_FILE}")

if __name__ == "__main__":
    pack()

